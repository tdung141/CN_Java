    private void btnAddSubjectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddSubjectActionPerformed
        int studentRow = dongSinhVienDangChon();
        if (studentRow < 0) {
            baoLoi("Hãy chọn một sinh viên trước khi nhập điểm môn.");
            return;
        }
        try {
            Subject m = docFormRaMon();
            Student s = studentModel.getStudentAt(studentRow);
            if (s.indexOfSubjectName(m.getName(), -1) >= 0) {
                throw new IllegalArgumentException("Sinh viên này đã có môn \"" + m.getName() + "\".");
            }

            subjectModel.addSubject(m);
            studentModel.refreshRow(studentRow); // cột Số môn và Điểm TB đổi theo
            luuFile();
            xoaTrangOMon();
            capNhatTomTat();
        } catch (IllegalArgumentException ex) {
            baoLoi(ex.getMessage());
        }
    }//GEN-LAST:event_btnAddSubjectActionPerformed

    private void btnEditSubjectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditSubjectActionPerformed
        int studentRow = dongSinhVienDangChon();
        int subjectRow = dongMonDangChon();
        if (studentRow < 0 || subjectRow < 0) {
            baoLoi("Hãy chọn một môn trong bảng dưới để sửa.");
            return;
        }
        try {
            Subject m = docFormRaMon();
            Student s = studentModel.getStudentAt(studentRow);
            // bỏ qua chính môn đang sửa khi kiểm tra trùng tên
            if (s.indexOfSubjectName(m.getName(), subjectRow) >= 0) {
                throw new IllegalArgumentException("Sinh viên này đã có môn \"" + m.getName() + "\".");
            }

            subjectModel.updateSubject(subjectRow, m);
            studentModel.refreshRow(studentRow);
            luuFile();
            capNhatTomTat();
        } catch (IllegalArgumentException ex) {
            baoLoi(ex.getMessage());
        }
    }//GEN-LAST:event_btnEditSubjectActionPerformed

