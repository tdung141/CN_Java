    /**
     * Đọc một ô chữ, cắt khoảng trắng hai đầu và kiểm tra rỗng.
     *
     * Chặn luôn dấu | vì file dữ liệu dùng ký tự này để phân cách cột, để lọt
     * vào thì lần sau đọc file lên sẽ sai.
     *
     * @throws IllegalArgumentException khi ô rỗng hoặc có dấu |
     */
    private String docTruongChu(JTextField field, String tenTruong) {
        String value = field.getText().trim();
        if (value.isEmpty()) {
            throw new IllegalArgumentException(tenTruong + " không được để trống.");
        }
        if (value.contains(StudentStorage.SEP)) {
            throw new IllegalArgumentException(tenTruong + " không được chứa ký tự \"" + StudentStorage.SEP + "\".");
        }
        return value;
    }

    /**
     * Đọc một ô điểm: phải là số và nằm trong khoảng 0 - 10.
     *
     * Cho gõ dấu phẩy thay dấu chấm vì bàn phím tiếng Việt hay quen kiểu 8,5.
     *
     * @throws IllegalArgumentException khi không phải số hoặc ngoài khoảng
     */
    private double docDiem(JTextField field, String tenTruong) {
        String text = field.getText().trim().replace(',', '.');
        if (text.isEmpty()) {
            throw new IllegalArgumentException(tenTruong + " không được để trống.");
        }
        double diem;
        try {
            diem = Double.parseDouble(text);
        } catch (NumberFormatException ex) {
            throw new IllegalArgumentException(tenTruong + " phải là số, ví dụ 8.5");
        }
        if (!QuyChe.diemHopLe(diem)) {
            throw new IllegalArgumentException(tenTruong + " phải nằm trong khoảng "
                    + (int) QuyChe.DIEM_MIN + " đến " + (int) QuyChe.DIEM_MAX + ".");
        }
        return diem;
    }

    /**
     * Đọc 4 ô của phần môn học rồi trả về một Subject.
     *
     * @throws IllegalArgumentException khi dữ liệu chưa hợp lệ
     */
    private Subject docFormRaMon() {
        String name = docTruongChu(txtSubjectName, "Tên môn");
        double cc = docDiem(txtCc, "Điểm chuyên cần");
        double gk = docDiem(txtGk, "Điểm giữa kỳ");
        double ck = docDiem(txtCk, "Điểm cuối kỳ");
        return new Subject(name, cc, gk, ck);
    }

    // ---------- đổi dòng trên bảng sang dòng trong model ----------

    /**
     * Đổi dòng đang chọn ở bảng sinh viên sang chỉ số dòng trong model.
     *
     * Phải đổi vì bảng có sắp xếp: dòng thứ 0 trên bảng chưa chắc là phần tử thứ
     * 0 trong danh sách.
     *
     * @return chỉ số dòng trong model, hoặc -1 nếu chưa chọn dòng nào
     */
    private int dongSinhVienDangChon() {
        int viewRow = tblStudents.getSelectedRow();
        if (viewRow < 0) {
            return -1;
        }
        return tblStudents.convertRowIndexToModel(viewRow);
    }

    /**
     * Đổi dòng đang chọn ở bảng điểm môn sang chỉ số dòng trong model.
     *
     * @return chỉ số dòng trong model, hoặc -1 nếu chưa chọn dòng nào
     */
    private int dongMonDangChon() {
        int viewRow = tblSubjects.getSelectedRow();
        if (viewRow < 0) {
            return -1;
        }
        return tblSubjects.convertRowIndexToModel(viewRow);
    }

    // ---------- phản ứng khi chọn dòng ----------

    /**
     * Chọn sinh viên nào thì đổ mã và họ tên lên form, đồng thời đổi luôn nội
     * dung bảng điểm môn sang sinh viên đó.
     */
    private void chonSinhVienThayDoi() {
        int row = dongSinhVienDangChon();
        if (row >= 0) {
            Student s = studentModel.getStudentAt(row);
            txtId.setText(s.getId());
            txtName.setText(s.getFullName());
            subjectModel.setStudent(s);
        } else {
            subjectModel.setStudent(null);
        }
        xoaTrangOMon();
        capNhatTrangThai();
    }

    /**
     * Chọn môn nào thì đổ 4 ô của môn đó lên form để sửa.
     */
    private void chonMonThayDoi() {
        int row = dongMonDangChon();
        if (row >= 0) {
            Subject m = subjectModel.getSubjectAt(row);
            txtSubjectName.setText(m.getName());
            txtCc.setText(hienSo(m.getChuyenCan()));
            txtGk.setText(hienSo(m.getGiuaKy()));
            txtCk.setText(hienSo(m.getCuoiKy()));
        }
        capNhatTrangThai();
    }

    // ---------- cập nhật trạng thái giao diện ----------

    /**
     * Bật tắt các nút theo tình trạng đang chọn dòng nào.
     *
     * Chưa chọn sinh viên thì không sửa xóa sinh viên được, cũng không nhập điểm
     * môn được vì chưa biết nhập cho ai. Chưa chọn môn thì không sửa xóa môn
     * được.
     */
    private void capNhatTrangThai() {
        boolean coSinhVien = dongSinhVienDangChon() >= 0;
        boolean coMon = coSinhVien && dongMonDangChon() >= 0;

        btnEdit.setEnabled(coSinhVien);
        btnDelete.setEnabled(coSinhVien);

        txtSubjectName.setEnabled(coSinhVien);
        txtCc.setEnabled(coSinhVien);
        txtGk.setEnabled(coSinhVien);
        txtCk.setEnabled(coSinhVien);

        btnAddSubject.setEnabled(coSinhVien);
        btnEditSubject.setEnabled(coMon);
        btnDeleteSubject.setEnabled(coMon);

        capNhatTomTat();
    }

    /**
     * Viết lại dòng tóm tắt phía trên bảng điểm môn.
     */
    private void capNhatTomTat() {
        int row = dongSinhVienDangChon();
        if (row < 0) {
            lblSummary.setText("Chưa chọn sinh viên nào. Chọn một dòng ở bảng trên để nhập điểm môn.");
            return;
        }
        Student s = studentModel.getStudentAt(row);
        if (s.getSubjectCount() == 0) {
            lblSummary.setText(s.getId() + " - " + s.getFullName() + "  |  chưa nhập môn nào");
            return;
        }
        lblSummary.setText(s.getId() + " - " + s.getFullName()
                + "  |  Số môn: " + s.getSubjectCount()
                + "  |  Điểm TB: " + QuyChe.lamTron2(s.getDiemTB())
                + "  |  Xếp loại: " + s.getRanking());
    }

    /**
     * Xóa trắng cả form và bỏ chọn dòng ở hai bảng.
     */
    private void lamMoiForm() {
        tblStudents.clearSelection();
        tblSubjects.clearSelection();
        txtId.setText("");
        txtName.setText("");
        xoaTrangOMon();
        capNhatTrangThai();
        txtId.requestFocusInWindow();
    }

    /**
     * Xóa trắng 4 ô của phần môn học và bỏ chọn dòng ở bảng điểm môn.
     */
    private void xoaTrangOMon() {
        tblSubjects.clearSelection();
        txtSubjectName.setText("");
        txtCc.setText("");
        txtGk.setText("");
        txtCk.setText("");
    }

    // ---------- đọc ghi file ----------

    /**
     * Đọc dữ liệu từ file lúc mở chương trình.
     *
     * File lỗi thì báo cho người dùng biết và mở với danh sách rỗng, nhưng khóa
     * việc ghi file lại để không làm mất dữ liệu cũ khi chưa được đồng ý.
     */
    private void docFile() {
        try {
            List<Student> students = StudentStorage.load();
            studentModel.setData(students);
        } catch (IOException ex) {
            logger.log(java.util.logging.Level.WARNING, "Không đọc được file dữ liệu", ex);
            choPhepLuu = false;
            JOptionPane.showMessageDialog(this,
                    ex.getMessage()
                    + "\n\nChương trình mở với danh sách rỗng."
                    + "\nLần đầu bạn thêm, sửa hay xóa sẽ được hỏi trước khi ghi đè file cũ.",
                    "Không đọc được dữ liệu", JOptionPane.WARNING_MESSAGE);
        }
    }

    /**
     * Ghi cả danh sách ra file sau mỗi lần thêm, sửa, xóa.
     */
    private void luuFile() {
        if (!choPhepLuu) {
            int traLoi = JOptionPane.showConfirmDialog(this,
                    "File " + StudentStorage.FILE_NAME + " cũ đang lỗi, ghi tiếp là mất nội dung cũ."
                    + "\nVẫn ghi đè?",
                    "Xác nhận ghi đè", JOptionPane.YES_NO_OPTION);
            if (traLoi != JOptionPane.YES_OPTION) {
                return;
            }
            choPhepLuu = true; // đã đồng ý một lần thì các lần sau ghi luôn
        }
        try {
            StudentStorage.save(studentModel.getData());
        } catch (IOException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Không ghi được file dữ liệu", ex);
            JOptionPane.showMessageDialog(this,
                    "Không ghi được file " + StudentStorage.filePath() + "\n" + ex.getMessage()
                    + "\n\nDữ liệu vẫn còn trên bảng nhưng chưa được lưu.",
                    "Lỗi ghi file", JOptionPane.ERROR_MESSAGE);
        }
    }

