    /**
     * Hiện số cho gọn: 9 thay vì 9.0, còn số lẻ thì giữ 2 chữ số thập phân.
     */
    private static String hienSo(double value) {
        double v = QuyChe.lamTron2(value);
        if (v == Math.rint(v)) {
            return String.valueOf((long) v);
        }
        return String.valueOf(v);
    }

